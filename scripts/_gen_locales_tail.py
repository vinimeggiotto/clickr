def ensure_locales(catalog: dict) -> dict:
    catalog = deep_merge({"locales": dict(LOCALE_LABELS)}, catalog)
    catalog["locales"] = dict(LOCALE_LABELS)
    return catalog


def main() -> None:
    ROOT.mkdir(parents=True, exist_ok=True)
    packs = {
        "pt-BR": PT,
        "en-US": EN,
        "zh-CN": ZH,
        "de-DE": DE,
        "es-ES": ES,
        "ru-RU": RU,
    }
    for code, data in packs.items():
        path = ROOT / f"{code}.json"
        payload = ensure_locales(data)
        path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print("wrote", path)


if __name__ == "__main__":
    main()
